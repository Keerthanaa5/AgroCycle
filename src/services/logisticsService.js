const BACKEND_BASE_URL = (typeof import.meta !== 'undefined' && import.meta.env && import.meta.env.VITE_BACKEND_URL) || 'http://localhost:5000/api/v1';

/**
 * Persists a consolidated shipment to the backend PostgreSQL database
 */
export async function syncShipmentToBackend(shipment, user) {
  if (!shipment) return null;
  const userId = user?.userId || user?.id || 'system';
  const role = user?.role || user?.activeRole || 'farmer';

  try {
    const res = await fetch(`${BACKEND_BASE_URL}/logistics/shipments`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-user-id': userId,
        'x-user-role': role,
        'Authorization': `Bearer ${userId}`
      },
      body: JSON.stringify(shipment)
    });

    if (res.ok) {
      const data = await res.json();
      return data.data;
    }
  } catch (err) {
    console.warn('[Logistics Backend Sync Warning]', err.message);
  }
  return null;
}

