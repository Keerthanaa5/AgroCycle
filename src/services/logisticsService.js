/**
 * Master deterministic logistics consolidation pipeline.
 *
 * @param {Object} params
 * @param {Object} params.buyerDemand - { crop, quantityRequiredKg, targetPrice, deliveryLocation }
 * @param {Array} params.farmers - Available farmer produce listings
 * @param {Array} params.drivers - Available drivers
 * @param {Array} params.vehicles - Available vehicles with capacityKg and driver info
 * @param {Object} [params.config] - Optional overrides (maxClusterDistanceKm, transportRatePerKm)
 * @returns {Object} Consolidation result { success, shipment, errorReason, cluster }
 */
export function consolidateSmartShipment({
  buyerDemand,
  farmers = [],
  drivers = [],
  vehicles = [],
  config = {}
} = {}) {
  const maxClusterDist = config.maxClusterDistanceKm || MAX_PICKUP_CLUSTER_DISTANCE_KM;
  const ratePerKm = config.transportRatePerKm || DEFAULT_TRANSPORT_RATE_PER_KM;

  if (!buyerDemand || !buyerDemand.crop || !buyerDemand.quantityRequiredKg) {
    return {
      success: false,
      errorReason: "Invalid buyer demand specification. Crop and quantity required are mandatory."
    };
  }

  const demandKg = Number(buyerDemand.quantityRequiredKg);
  const targetPrice = Number(buyerDemand.targetPrice || 28);
  const buyerLoc = buyerDemand.deliveryLocation || {
    lat: 9.9195,
    lng: 78.1217,
    city: "Madurai",
    district: "Madurai",
    state: "Tamil Nadu",
    businessName: buyerDemand.businessName || "Vaigai Food Processors"
  };

  // 1. Filter compatible farmers
  const compatibleFarmers = filterCompatibleFarmers(farmers, buyerDemand);
  if (compatibleFarmers.length === 0) {
    return {
      success: false,
      errorReason: `No compatible farmers found with available "${buyerDemand.crop}" stock.`
    };
  }

  // 2. Geographic clustering
  const clusters = clusterFarmersGeographically(compatibleFarmers, maxClusterDist);
  if (clusters.length === 0) {
    return {
      success: false,
      errorReason: `No geographic clusters of farmers found within ${maxClusterDist} km threshold.`
    };
  }

  // Pick best cluster (highest volume)
  const bestCluster = clusters[0];

  // 3. Demand fulfillment & partial allocation
  const fulfillment = matchDemandWithFarmers(bestCluster.farmers, demandKg);
  if (fulfillment.allocatedFarmers.length === 0) {
    return {
      success: false,
      errorReason: "Could not allocate produce from cluster farmers to satisfy requirement."
    };
  }

  const totalConsolidatedKg = fulfillment.totalAllocatedQuantityKg;

  // 4. Vehicle & Driver selection
  const optimalVehicle = selectOptimalVehicle(vehicles, totalConsolidatedKg);
  if (!optimalVehicle) {
    const maxAvailCapacity = vehicles.reduce((max, v) => Math.max(max, Number(v.capacityKg || 0)), 0);
    return {
      success: false,
      errorReason: `No available vehicle has sufficient capacity for ${totalConsolidatedKg.toLocaleString()} kg. (Maximum available vehicle capacity is ${maxAvailCapacity.toLocaleString()} kg).`,
      requiredQuantityKg: totalConsolidatedKg,
      maxAvailableCapacityKg: maxAvailCapacity
    };
  }

  // Resolve driver info
  const driver = drivers.find((d) => d.driverId === optimalVehicle.driverId) || {
    driverId: optimalVehicle.driverId || "drv_ravi",
    name: optimalVehicle.driverName || "Ravi",
    phone: "9876543290",
    location: optimalVehicle.currentLocation || { lat: 9.9280, lng: 78.1150, address: "Madurai Logistics Hub" }
  };

  const driverStartLoc = driver.location || { lat: 9.9280, lng: 78.1150, address: "Madurai Logistics Hub" };

  // 5. Route generation (Nearest Neighbour)
  const route = buildConsolidatedRoute(driverStartLoc, fulfillment.allocatedFarmers, buyerLoc);

  // 6. Transport cost calculation
  const totalTransportCost = calculateTransportCost(route.totalEstimatedDistanceKm, ratePerKm);
  const transportCostPerKg = calculateTransportCostPerKg(totalTransportCost, totalConsolidatedKg);

  // 7. Proportional transport share allocation to farmers
  const allocatedFarmersWithShares = allocateTransportCostToFarmers(
    fulfillment.allocatedFarmers,
    totalTransportCost,
    totalConsolidatedKg
  );

  // 8. Net Expected Value calculations
  const netValueBreakdowns = allocatedFarmersWithShares.map((f) =>
    calculateFarmerNetExpectedValue(f, targetPrice, f.transportShare)
  );

  // 9. Construct Final Shipment Record
  const shipmentId = `shipment_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
  const shipment = {
    shipmentId,
    buyerId: buyerDemand.buyerId || "usr_buyer_vaigai",
    buyerName: buyerDemand.businessName || "Vaigai Food Processors",
    crop: buyerDemand.crop,
    demandQuantityKg: demandKg,
    totalQuantityKg: totalConsolidatedKg,
    isFullyFulfilled: fulfillment.isFulfilled,
    farmerAllocations: allocatedFarmersWithShares,
    netValueBreakdowns,
    driverId: driver.driverId,
    driverName: driver.name,
    driverPhone: driver.phone,
    vehicleId: optimalVehicle.vehicleId,
    vehicleType: optimalVehicle.vehicleType || VEHICLE_TYPES.HEAVY_TRUCK,
    vehicleCapacityKg: optimalVehicle.vehicleCapacityKg,
    vehicleUtilizationPercent: optimalVehicle.vehicleUtilizationPercent,
    estimatedDistanceKm: route.totalEstimatedDistanceKm,
    estimatedTransportCost: totalTransportCost,
    transportRatePerKm: ratePerKm,
    transportCostPerKg: transportCostPerKg,
    route,
    currentStopIndex: 0,
    status: SHIPMENT_STATUS.MATCHED,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString()
  };

  return {
    success: true,
    shipment,
    cluster: bestCluster
  };
}

