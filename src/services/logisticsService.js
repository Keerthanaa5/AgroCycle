/**
 * Filters available farmers compatible with the buyer's commodity requirement.
 *
 * @param {Array} farmers - List of farmer records
 * @param {Object} buyerDemand - Buyer requirement object
 * @returns {Array} List of matching farmers
 */
export function filterCompatibleFarmers(farmers = [], buyerDemand = {}) {
  if (!Array.isArray(farmers) || !buyerDemand || !buyerDemand.crop) {
    return [];
  }

  const demandCropNorm = normalizeCropName(buyerDemand.crop);
  const demandCanonical = KNOWN_CROP_ALIASES[demandCropNorm] || demandCropNorm;

  return farmers.filter((farmer) => {
    if (!farmer || typeof farmer !== "object") return false;

    // 1. Crop Match
    const fCropNorm = normalizeCropName(farmer.crop || farmer.crop_type || farmer.commodity || "");
    const fCanonical = KNOWN_CROP_ALIASES[fCropNorm] || fCropNorm;
    if (fCanonical !== demandCanonical) return false;

    // 2. Quantity Available > 0
    const qty = Number(farmer.quantityKg || farmer.quantity_kg || farmer.quantity || 0);
    if (qty <= 0) return false;

    // 3. Location validity
    const loc = farmer.location || {};
    const lat = loc.lat ?? loc.latitude;
    const lng = loc.lng ?? loc.longitude;
    if (typeof lat !== "number" || typeof lng !== "number") return false;

    // 4. Quality compatibility (if specified in demand)
    if (buyerDemand.quality && farmer.quality && farmer.quality !== "any") {
      if (buyerDemand.quality.toLowerCase() !== farmer.quality.toLowerCase()) {
        return false;
      }
    }

    return true;
  });
}

