// 8. FARMER NET EXPECTED VALUE CALCULATION
// ==============================================================================

/**
 * Calculates each farmer's estimated Gross Revenue, Expected Losses, and Net Expected Value.
 *
 * Formula:
 * Gross Revenue = Agreed Price/kg × Allocated Qty
 * Net Expected Value = Gross Revenue - Transport Share - Expected Shrinkage Loss - Expected Rejection Loss - Platform Fee
 *
 * @param {Object} farmerAllocation - Farmer allocation with allocatedQuantityKg and transportShare
 * @param {number} agreedPricePerKg - Agreed price per kg (₹)
 * @param {number} transportShare - Farmer's allocated transport share (₹)
 * @param {Object} [lossOptions] - Optional loss parameters
 * @param {number} [lossOptions.shrinkageRate=0.015] - Estimated transit shrinkage loss (e.g. 1.5%)
 * @param {number} [lossOptions.rejectionProbability=0.01] - Estimated rejection risk (e.g. 1.0%)
 * @param {number} [lossOptions.platformFee=0] - Optional platform fee
 * @returns {Object} Complete Net Expected Value breakdown
 */
export function calculateFarmerNetExpectedValue(
  farmerAllocation,
  agreedPricePerKg = 0,
  transportShare = 0,
  lossOptions = {}
) {
  const qty = Number(farmerAllocation?.allocatedQuantityKg || 0);
  const price = Number(agreedPricePerKg || farmerAllocation?.pricePerKg || 0);
  const transport = Number(transportShare ?? farmerAllocation?.transportShare ?? 0);

  const shrinkageRate = Number(lossOptions.shrinkageRate ?? 0.015); // 1.5% default transit moisture/shrinkage
  const rejectionProb = Number(lossOptions.rejectionProbability ?? 0.01); // 1.0% default quality rejection probability
  const platformFee = Number(lossOptions.platformFee ?? 0);

  const grossRevenue = Math.round(price * qty * 100) / 100;
  const expectedShrinkageLoss = Math.round(grossRevenue * shrinkageRate * 100) / 100;
  const expectedRejectionLoss = Math.round(grossRevenue * rejectionProb * 100) / 100;
  const totalExpectedLosses = Math.round((expectedShrinkageLoss + expectedRejectionLoss) * 100) / 100;

  const netExpectedValue = Math.round((grossRevenue - transport - totalExpectedLosses - platformFee) * 100) / 100;
  const netRealizedPerKg = qty > 0 ? Math.round((netExpectedValue / qty) * 100) / 100 : 0;

  return {
    farmerId: farmerAllocation?.farmerId,
    farmerName: farmerAllocation?.farmerName,
    crop: farmerAllocation?.crop,
    allocatedQuantityKg: qty,
    pricePerKg: price,
    grossRevenue,
    transportShare: transport,
    expectedShrinkageLoss,
    expectedRejectionLoss,
    totalExpectedLosses,
    platformFee,
    netExpectedValue,
    netRealizedPerKg
  };
}

