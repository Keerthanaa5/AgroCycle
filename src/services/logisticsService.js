const VALID_TRANSITIONS = {
  [SHIPMENT_STATUS.MATCHED]: [SHIPMENT_STATUS.DRIVER_ASSIGNED, SHIPMENT_STATUS.CANCELLED],
  [SHIPMENT_STATUS.DRIVER_ASSIGNED]: [SHIPMENT_STATUS.READY_FOR_PICKUP, SHIPMENT_STATUS.CANCELLED],
  [SHIPMENT_STATUS.READY_FOR_PICKUP]: [SHIPMENT_STATUS.IN_TRANSIT, SHIPMENT_STATUS.CANCELLED],
  [SHIPMENT_STATUS.IN_TRANSIT]: [SHIPMENT_STATUS.DELIVERED, SHIPMENT_STATUS.CANCELLED],
  [SHIPMENT_STATUS.DELIVERED]: [],
  [SHIPMENT_STATUS.CANCELLED]: []
};

/**
 * Executes a verified state transition on a shipment.
 *
 * @param {Object} shipment - Active shipment record
 * @param {string} nextStatus - Next target status
 * @param {Object} [metadata] - Optional metadata updates (e.g. currentStopIndex, notes)
 * @returns {Object} Updated shipment or throws Error if invalid transition
 */
export function transitionShipmentStatus(shipment, nextStatus, metadata = {}) {
  if (!shipment || !shipment.status) {
    throw new Error("Invalid shipment object.");
  }

  const allowed = VALID_TRANSITIONS[shipment.status] || [];
  if (!allowed.includes(nextStatus)) {
    throw new Error(`Invalid shipment state transition from "${shipment.status}" to "${nextStatus}".`);
  }

  const updated = {
    ...shipment,
    ...metadata,
    status: nextStatus,
    updatedAt: new Date().toISOString()
  };

  // Persist update in localDB & IndexedDB
  saveShipment(updated);

  // Enqueue offline sync action
  enqueueAction({
    userId: shipment.driverId || "system",
    actionType: ACTION_TYPES.UPDATE_LOGISTICS_SHIPMENT_STATUS,
    entityType: "logisticsShipments",
    entityId: updated.shipmentId,
    payload: updated
  }).catch(() => {});

  return updated;
}

