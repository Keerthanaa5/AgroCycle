export function getShipments() {
  return localDB.getData(KEYS.LOGISTICS_SHIPMENTS) || [];
}

export function getShipmentById(shipmentId) {
  const shipments = getShipments();
  return shipments.find((s) => s.shipmentId === shipmentId) || null;
}

export function saveShipment(shipment) {
  if (!shipment || !shipment.shipmentId) return;
  const existing = getShipments();
  const idx = existing.findIndex((s) => s.shipmentId === shipment.shipmentId);
  if (idx >= 0) {
    existing[idx] = shipment;
    localDB.saveData(KEYS.LOGISTICS_SHIPMENTS, existing);
  } else {
    localDB.saveData(KEYS.LOGISTICS_SHIPMENTS, [shipment, ...existing]);
  }
}

