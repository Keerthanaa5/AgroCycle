/**
 * Selects the optimal available vehicle/driver that satisfies load capacity
 * while maximizing capacity utilization (avoids unnecessarily oversized trucks).
 *
 * @param {Array} vehicles - Available vehicle records with attached driver
 * @param {number} totalQuantityKg - Total consolidated load in kg
 * @returns {Object|null} Selected vehicle object with utilization percentage, or null if none fit.
 */
export function selectOptimalVehicle(vehicles = [], totalQuantityKg = 0) {
  if (!Array.isArray(vehicles) || vehicles.length === 0 || totalQuantityKg <= 0) {
    return null;
  }

  // Filter feasible vehicles: capacity >= load and status == AVAILABLE
  const feasible = vehicles.filter((v) => {
    const cap = Number(v.capacityKg || v.capacity || 0);
    const isAvail = !v.status || v.status === DRIVER_STATUS.AVAILABLE;
    return cap >= totalQuantityKg && isAvail;
  });

  if (feasible.length === 0) {
    return null;
  }

  // Sort by smallest excess capacity (highest utilization)
  feasible.sort((a, b) => {
    const capA = Number(a.capacityKg || a.capacity || 0);
    const capB = Number(b.capacityKg || b.capacity || 0);
    return capA - capB;
  });

  const selected = feasible[0];
  const cap = Number(selected.capacityKg || selected.capacity || 0);
  const utilization = Math.round((totalQuantityKg / cap) * 10000) / 100; // e.g. 83.33%

  return {
    ...selected,
    vehicleCapacityKg: cap,
    vehicleUtilizationPercent: utilization
  };
}

