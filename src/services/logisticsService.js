/**
 * Allocates quantities from candidate farmers to satisfy the buyer's requirement exactly.
 * Supports partial allocation so farmers are not over-committed.
 *
 * @param {Array} candidateFarmers - List of farmers in the selected cluster
 * @param {number} demandQuantityKg - Total demand requested by buyer (kg)
 * @returns {Object} { allocatedFarmers, totalAllocatedQuantityKg, remainingUnsatisfiedKg, isFulfilled }
 */
export function matchDemandWithFarmers(candidateFarmers = [], demandQuantityKg = 0) {
  const targetDemand = Number(demandQuantityKg);
  if (isNaN(targetDemand) || targetDemand <= 0 || !Array.isArray(candidateFarmers)) {
    return {
      allocatedFarmers: [],
      totalAllocatedQuantityKg: 0,
      remainingUnsatisfiedKg: targetDemand || 0,
      isFulfilled: false
    };
  }

  let remainingDemand = targetDemand;
  const allocatedFarmers = [];

  for (const farmer of candidateFarmers) {
    if (remainingDemand <= 0) break;

    const availableKg = Number(farmer.quantityKg || farmer.quantity_kg || farmer.quantity || 0);
    if (availableKg <= 0) continue;

    const allocatedKg = Math.min(availableKg, remainingDemand);
    const remainingUnallocatedKg = availableKg - allocatedKg;

    allocatedFarmers.push({
      farmerId: farmer.id || farmer.farmerId || `farmer_${allocatedFarmers.length + 1}`,
      farmerName: farmer.name || farmer.farmerName || `Farmer ${allocatedFarmers.length + 1}`,
      crop: farmer.crop || farmer.crop_type || "Tomato",
      availableQuantityKg: availableKg,
      allocatedQuantityKg: allocatedKg,
      remainingQuantityKg: remainingUnallocatedKg,
      pricePerKg: Number(farmer.pricePerKg || farmer.price_per_kg || farmer.price || 25),
      location: farmer.location,
      phone: farmer.phone || "N/A"
    });

    remainingDemand -= allocatedKg;
  }

  const totalAllocated = targetDemand - remainingDemand;
  const isFulfilled = remainingDemand === 0;

  return {
    allocatedFarmers,
    totalAllocatedQuantityKg: totalAllocated,
    remainingUnsatisfiedKg: Math.max(0, remainingDemand),
    isFulfilled
  };
}

