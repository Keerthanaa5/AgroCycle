/**
 * Calculates estimated transport cost based on route distance and rate per km.
 *
 * @param {number} estimatedDistanceKm - Total route distance
 * @param {number} ratePerKm - Configurable rate per km (default ₹60/km)
 * @returns {number} Total estimated transport cost in ₹
 */
export function calculateTransportCost(estimatedDistanceKm = 0, ratePerKm = DEFAULT_TRANSPORT_RATE_PER_KM) {
  const dist = Number(estimatedDistanceKm) || 0;
  const rate = Number(ratePerKm) || DEFAULT_TRANSPORT_RATE_PER_KM;
  return Math.round(dist * rate * 100) / 100;
}

/**
 * Calculates transport cost per kg.
 *
 * @param {number} totalTransportCost - Total transport cost (₹)
 * @param {number} totalQuantityKg - Total shipment quantity (kg)
 * @returns {number} Transport cost per kg (₹/kg)
 */
export function calculateTransportCostPerKg(totalTransportCost = 0, totalQuantityKg = 0) {
  const cost = Number(totalTransportCost) || 0;
  const qty = Number(totalQuantityKg) || 0;
  if (qty <= 0) return 0;
  return Math.round((cost / qty) * 10000) / 10000;
}

/**
 * Distributes the total transport cost proportionally across farmers based on allocated quantity.
 * Applies exact floating-point sum correction so the sum of farmer shares exactly equals totalTransportCost.
 *
 * @param {Array} allocatedFarmers - List of allocated farmer objects
 * @param {number} totalTransportCost - Total transport cost (₹)
 * @param {number} totalQuantityKg - Total shipment quantity (kg)
 * @returns {Array} Allocated farmers with exact transportShare field
 */
export function allocateTransportCostToFarmers(allocatedFarmers = [], totalTransportCost = 0, totalQuantityKg = 0) {
  if (!Array.isArray(allocatedFarmers) || allocatedFarmers.length === 0 || totalQuantityKg <= 0) {
    return [];
  }

  const cost = Number(totalTransportCost) || 0;
  const totalQty = Number(totalQuantityKg) || 1;

  let assignedSum = 0;
  const withShares = allocatedFarmers.map((f) => {
    const proportion = f.allocatedQuantityKg / totalQty;
    const share = Math.round(cost * proportion * 100) / 100;
    assignedSum += share;
    return {
      ...f,
      transportShare: share,
      transportSharePerKg: Math.round((share / f.allocatedQuantityKg) * 10000) / 10000
    };
  });

  // Floating-point rounding correction: adjust difference onto the farmer with the largest share
  const diff = Math.round((cost - assignedSum) * 100) / 100;
  if (Math.abs(diff) > 0 && withShares.length > 0) {
    let maxIdx = 0;
    let maxAlloc = -1;
    for (let i = 0; i < withShares.length; i++) {
      if (withShares[i].allocatedQuantityKg > maxAlloc) {
        maxAlloc = withShares[i].allocatedQuantityKg;
        maxIdx = i;
      }
    }
    withShares[maxIdx].transportShare = Math.round((withShares[maxIdx].transportShare + diff) * 100) / 100;
  }

  return withShares;
}

