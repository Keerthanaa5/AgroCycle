// 3. GEOGRAPHIC CLUSTERING
// ==============================================================================

/**
 * Groups nearby compatible farmers into geographic clusters using deterministic proximity.
 *
 * @param {Array} farmers - Filtered compatible farmers
 * @param {number} maxClusterDistanceKm - Configurable cluster threshold (default 25 km)
 * @returns {Array} Array of candidate clusters, each with { clusterId, farmers, totalAvailableKg, centerLat, centerLng }
 */
export function clusterFarmersGeographically(farmers = [], maxClusterDistanceKm = MAX_PICKUP_CLUSTER_DISTANCE_KM) {
  if (!Array.isArray(farmers) || farmers.length === 0) {
    return [];
  }

  const unassigned = [...farmers];
  const clusters = [];
  let clusterIdx = 1;

  while (unassigned.length > 0) {
    // Select seed farmer (anchor)
    const seed = unassigned.shift();
    const seedLoc = seed.location || {};
    const seedLat = seedLoc.lat ?? seedLoc.latitude;
    const seedLng = seedLoc.lng ?? seedLoc.longitude;

    const currentClusterFarmers = [seed];
    const remaining = [];

    for (const other of unassigned) {
      const oLoc = other.location || {};
      const oLat = oLoc.lat ?? oLoc.latitude;
      const oLng = oLoc.lng ?? oLoc.longitude;

      const d = calculateHaversineDistanceKm(seedLat, seedLng, oLat, oLng);
      if (d !== null && d <= maxClusterDistanceKm) {
        currentClusterFarmers.push(other);
      } else {
        remaining.push(other);
      }
    }

    // Compute cluster centroid and aggregate volume
    let sumLat = 0;
    let sumLng = 0;
    let totalKg = 0;

    for (const f of currentClusterFarmers) {
      const loc = f.location || {};
      sumLat += loc.lat ?? loc.latitude;
      sumLng += loc.lng ?? loc.longitude;
      totalKg += Number(f.quantityKg || f.quantity_kg || f.quantity || 0);
    }

    clusters.push({
      clusterId: `cluster_${clusterIdx++}`,
      farmers: currentClusterFarmers,
      totalAvailableKg: totalKg,
      centerLat: Math.round((sumLat / currentClusterFarmers.length) * 10000) / 10000,
      centerLng: Math.round((sumLng / currentClusterFarmers.length) * 10000) / 10000,
      farmerCount: currentClusterFarmers.length
    });

    unassigned.length = 0;
    unassigned.push(...remaining);
  }

  // Sort clusters by highest available quantity first
  clusters.sort((a, b) => b.totalAvailableKg - a.totalAvailableKg);
  return clusters;
}

