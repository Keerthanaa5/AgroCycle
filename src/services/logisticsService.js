// 6. ROUTE GENERATION (NEAREST-NEIGHBOUR ESTIMATED ROUTE)
// ==============================================================================

/**
 * Builds a deterministic route starting at the driver's location, visiting all pickup farmers
 * using nearest-neighbour order, and finishing at the buyer's delivery point.
 *
 * @param {Object} driverLocation - Driver start { lat, lng, address }
 * @param {Array} allocatedFarmers - List of allocated farmer objects
 * @param {Object} buyerLocation - Buyer delivery location { lat, lng, address }
 * @returns {Object} Route object with stops, leg distances, and total estimated distance.
 */
export function buildConsolidatedRoute(driverLocation, allocatedFarmers = [], buyerLocation) {
  if (!driverLocation || !buyerLocation || !Array.isArray(allocatedFarmers) || allocatedFarmers.length === 0) {
    return {
      stops: [],
      totalEstimatedDistanceKm: 0,
      legs: []
    };
  }

  const dLat = driverLocation.lat ?? driverLocation.latitude;
  const dLng = driverLocation.lng ?? driverLocation.longitude;

  // Support single buyer or array of multiple buyers
  const buyerList = Array.isArray(buyerLocation) 
    ? buyerLocation 
    : [buyerLocation];

  const unvisitedFarmers = [...allocatedFarmers];
  const unvisitedBuyers = [...buyerList];
  const stops = [];
  const legs = [];

  const totalCargoKg = allocatedFarmers.reduce((sum, f) => sum + (Number(f.allocatedQuantityKg) || 0), 0);
  let currentCargoKg = 0;

  // Stop 0: Driver Start
  stops.push({
    stopIndex: 0,
    stopType: "DRIVER_START",
    name: "Driver Starting Location",
    location: driverLocation,
    coordinates: { lat: dLat, lng: dLng },
    quantityKg: 0,
    cumulativeLoadKg: 0,
    estimatedDistanceToNextKm: 0
  });

  let currentLat = dLat;
  let currentLng = dLng;
  let totalDistanceKm = 0;

  // 1. Visit all farmers in nearest-neighbour order
  while (unvisitedFarmers.length > 0) {
    let nearestIdx = 0;
    let minDistance = Infinity;

    for (let i = 0; i < unvisitedFarmers.length; i++) {
      const f = unvisitedFarmers[i];
      const loc = f.location || f.pickupCoordinates || {};
      const fLat = loc.lat ?? loc.latitude;
      const fLng = loc.lng ?? loc.longitude;

      const dist = calculateHaversineDistanceKm(currentLat, currentLng, fLat, fLng);
      if (dist !== null && dist < minDistance) {
        minDistance = dist;
        nearestIdx = i;
      }
    }

    const nextFarmer = unvisitedFarmers.splice(nearestIdx, 1)[0];
    const nextLoc = nextFarmer.location || nextFarmer.pickupCoordinates || {};
    const nextLat = nextLoc.lat ?? nextLoc.latitude;
    const nextLng = nextLoc.lng ?? nextLoc.longitude;

    const legDist = Math.round(minDistance * 100) / 100;
    totalDistanceKm += legDist;
    currentCargoKg += (Number(nextFarmer.allocatedQuantityKg) || 0);

    legs.push({
      fromStop: stops[stops.length - 1].name,
      toStop: `Pickup: ${nextFarmer.farmerName}`,
      distanceKm: legDist
    });

    stops[stops.length - 1].estimatedDistanceToNextKm = legDist;

    stops.push({
      stopIndex: stops.length,
      stopType: "PICKUP",
      id: nextFarmer.farmerId,
      farmerId: nextFarmer.farmerId,
      name: `Pickup: ${nextFarmer.farmerName}`,
      farmerName: nextFarmer.farmerName,
      crop: nextFarmer.crop,
      quantityKg: nextFarmer.allocatedQuantityKg,
      cumulativeLoadKg: currentCargoKg,
      coordinates: { lat: nextLat, lng: nextLng },
      location: nextLoc,
      status: "PENDING",
      estimatedDistanceToNextKm: 0
    });

    currentLat = nextLat;
    currentLng = nextLng;
  }

  // 2. Deliver to all buyers in nearest-neighbour order
  while (unvisitedBuyers.length > 0) {
    let nearestBuyerIdx = 0;
    let minBuyerDist = Infinity;

    for (let i = 0; i < unvisitedBuyers.length; i++) {
      const b = unvisitedBuyers[i];
      const bLoc = b.deliveryLocation || b.deliveryCoordinates || b.location || b;
      const bLat = bLoc.lat ?? bLoc.latitude;
      const bLng = bLoc.lng ?? bLoc.longitude;

      const dist = calculateHaversineDistanceKm(currentLat, currentLng, bLat, bLng);
      if (dist !== null && dist < minBuyerDist) {
        minBuyerDist = dist;
        nearestBuyerIdx = i;
      }
    }

    const nextBuyer = unvisitedBuyers.splice(nearestBuyerIdx, 1)[0];
    const bLoc = nextBuyer.deliveryLocation || nextBuyer.deliveryCoordinates || nextBuyer.location || nextBuyer;
    const bLat = bLoc.lat ?? bLoc.latitude;
    const bLng = bLoc.lng ?? bLoc.longitude;

    const legDist = Math.round(minBuyerDist * 100) / 100;
    totalDistanceKm += legDist;
    const buyerDropQty = Number(nextBuyer.quantityKg || nextBuyer.quantityRequiredKg || currentCargoKg);
    currentCargoKg = Math.max(0, currentCargoKg - buyerDropQty);

    legs.push({
      fromStop: stops[stops.length - 1].name,
      toStop: `Delivery: ${nextBuyer.buyerName || nextBuyer.businessName || "Buyer Facility"}`,
      distanceKm: legDist
    });

    stops[stops.length - 1].estimatedDistanceToNextKm = legDist;

    stops.push({
      stopIndex: stops.length,
      stopType: "DELIVERY",
      id: nextBuyer.buyerId || nextBuyer.id,
      buyerId: nextBuyer.buyerId || nextBuyer.id,
      name: `Delivery: ${nextBuyer.buyerName || nextBuyer.businessName || "Buyer Facility"}`,
      buyerName: nextBuyer.buyerName || nextBuyer.businessName || "Buyer Facility",
      quantityKg: buyerDropQty,
      cumulativeLoadKg: currentCargoKg,
      coordinates: { lat: bLat, lng: bLng },
      location: bLoc,
      status: "PENDING",
      estimatedDistanceToNextKm: 0
    });

    currentLat = bLat;
    currentLng = bLng;
  }

  return {
    stops,
    legs,
    totalStops: stops.length,
    totalEstimatedDistanceKm: Math.round(totalDistanceKm * 100) / 100
  };
}

